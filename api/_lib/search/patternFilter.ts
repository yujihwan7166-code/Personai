import type { SearchDecision } from './types.js';

// ── 검색 확실히 불필요 패턴 ──
const NO_SEARCH_PATTERNS: RegExp[] = [
  // 인사/감정
  /^(안녕|하이|헬로|hi|hello|hey)\b/i,
  /^(고마워|감사|땡큐|thank)/i,
  /(ㅋ{2,}|ㅎ{2,}|ㅠ{2,}|ㅜ{2,}|ㅇㅇ|ㄴㄴ|ㄱㄱ)/,
  /^(응|네|예|아니|ㅇ|ㄴ|그래|맞아|좋아|오키|ㅇㅋ|ok|yes|no|nope|sure)\b/i,
  /(기분이|우울|심심|외로|사랑해|보고싶|행복해|슬퍼|화나|짜증)/,
  // 역할/창작 요청
  /(써줘|만들어줘|그려줘|작성해줘|번역해줘|요약해줘|정리해줘|변환해줘|코딩해줘)/,
  /(역할극|이야기|소설|시\s*써|랩\s*써|편지|일기|대본)/,
  // 철학/추상 (시사 무관)
  /^(인생이란|사랑이란|행복이란|삶이란|죽음이란)/,
  /(의미가\s*뭐|철학적|윤리적|도덕적).*(설명|알려)/,
  // 플랫폼 메타 질문
  /(너\s*누구|넌\s*뭐|어떤\s*AI|뭘\s*할\s*수|너의\s*이름)/,
  // 단순 이어가기
  /^(계속|더|왜\??|어떻게\??|그래서\??|진짜\??|정말\??|ㄹㅇ\??)\s*$/,
  /^.{1,5}$/,  // 5자 이하 짧은 응답
  // 수학/코딩/학습 (실시간 불필요)
  /^(피타고라스|미적분|함수|방정식|알고리즘|자료구조|디자인패턴)/,
  /(풀어줘|계산해줘|증명해줘|코드\s*리뷰|디버깅|버그)/,
  /(설명해\s*줘|개념|원리|이론|공식|정의가\s*뭐)/,
];

// ── 검색 확실히 필요 패턴 ──
const SEARCH_REQUIRED_PATTERNS: RegExp[] = [
  // 시세/가격
  /(비트코인|이더리움|코인|주가|환율|금값|유가|시세|몇\s*원|얼마야)/,
  /(주식|나스닥|코스피|코스닥|다우|S&P|s&p)/i,
  // 날씨
  /(날씨|기온|비\s*와|비\s*오|눈\s*와|미세먼지|자외선|태풍)/,
  // 최신 뉴스 명시
  /(오늘\s*뉴스|최근\s*소식|방금|속보|발표했|보도|기사)/,
  /(최신|최근|요즘|근황|현재\s*상황|지금\s*상황)/,
  // 시간 민감 + 고유명사
  /(현재\s*대통령|지금\s*CEO|올해|금년|이번\s*달|이번\s*주)/,
  /(202[4-9]년|2030년)/,
  // 스포츠 결과
  /(경기\s*결과|누가\s*이겼|몇\s*대\s*몇|승리|우승|순위)/,
  /(월드컵|올림픽|챔피언스리그|프리미어리그|KBO|K리그|NBA|MLB)/i,
  // 선거/정치 현황
  /(대선|총선|탄핵|지지율|국회|정부|대통령|장관)/,
  // 사건/사고
  /(사건|사고|지진|전쟁|침공|폭발|테러|재난|사망)/,
  // 제품/서비스 현황
  /(출시|업데이트|패치|버전|신제품|가격\s*인상|가격\s*인하)/,
  // 인물 근황
  /(근황|뭐\s*하고\s*있|어떻게\s*됐|무슨\s*일|사퇴|취임|체포|결혼|이혼)/,
];

export function shouldSearch(message: string): SearchDecision {
  const trimmed = message.trim();

  // 빈 메시지
  if (!trimmed) return 'SEARCH_NOT_NEEDED';

  // 불필요 패턴 먼저 체크
  for (const pattern of NO_SEARCH_PATTERNS) {
    if (pattern.test(trimmed)) return 'SEARCH_NOT_NEEDED';
  }

  // 필요 패턴 체크
  for (const pattern of SEARCH_REQUIRED_PATTERNS) {
    if (pattern.test(trimmed)) return 'SEARCH_REQUIRED';
  }

  return 'UNCERTAIN';
}

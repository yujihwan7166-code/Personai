let __idCounter = 0;
function sid(prefix: string) {
  __idCounter += 1;
  return `${prefix}-sample-${Date.now().toString(36)}-${__idCounter}`;
}

/** 공통 필드 빌더. */
function makeSource(title: string, content: string): StudySource {
  return {
    id: sid('src'),
    kind: 'paste',
    title,
    content,
    addedAt: Date.now(),
    enabled: true,
    status: 'ready',
    renderMode: 'text',
  };
}

function makeLensOutput(lens: LensOutput['lens'], content: string): LensOutput {
  return {
    lens,
    content,
    tone: 'plain',
    level: 'standard',
    generatedAt: Date.now(),
  };
}

function makeFlashcard(front: string, back: string, concept?: string): Flashcard {
  return {
    id: sid('fc'),
    front,
    back,
    concept,
    ease: 2.5,
    intervalDays: 1,
    dueAt: Date.now(),
    reviewsCount: 0,
    source: 'ai',
  };
}

function makeQuiz(question: string, choices: string[], answerIndex: number, explanation: string, concept?: string): StudyQuizItem {
  return {
    id: sid('q'),
    question,
    choices,
    answerIndex,
    explanation,
    concept,
  };
}


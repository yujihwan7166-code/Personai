/** 이미 시드했는지 확인. */
export function isSeeded(): boolean {
  try {
    return localStorage.getItem(SEED_FLAG_KEY) === '1';
  } catch {
    return true; // SSR/차단 환경에선 시드 스킵
  }
}

/** 시드 플래그 설정. */
export function markSeeded(): void {
  try { localStorage.setItem(SEED_FLAG_KEY, '1'); } catch { /* noop */ }
}

/** 시드 초기화 — 설정 "샘플 다시 보기" 용. */
export function resetSeedFlag(): void {
  try { localStorage.removeItem(SEED_FLAG_KEY); } catch { /* noop */ }
}

/** 샘플 노트북인지 판별. */
export function isSampleNotebook(notebook: { description?: string }): boolean {
  return !!notebook.description?.includes(SAMPLE_DESC_TOKEN);
}

/** 샘플에서 UI 표시용 description (토큰 제거). */
export function displayDescription(description?: string): string | undefined {
  if (!description) return description;
  return description.replace(SAMPLE_DESC_TOKEN, '').trim();
}

/**
 * 처음 여는 서재 — 다섯 권.
 *
 * 빈 서재는 이 방이 무엇을 하는 방인지 알려주지 못한다. 그렇다고 '예시입니다' 하고
 * 티 나는 껍데기를 넣으면 지우고 시작하게 된다. 그래서 **그냥 쓸 만한 책**을 넣는다 —
 * 처음부터 여기 꽂혀 있던 것처럼.
 *
 * 다섯 권을 고른 기준
 *  · 분야가 서로 안 겹칠 것 (감각 · 돈 · 몸 · 기술 · 살림)
 *  · 각각이 이 방의 다른 기능을 보여줄 것
 *      커피    — 인포박스(수치 요약)와 '문제 → 원인' 그물
 *      돈      — 위계가 깊고 서로 참조가 많은 글
 *      몸      — 동작마다 인포박스, 안전 경고
 *      사진    — 세 값이 서로 물리는 관계형 링크
 *      살림    — 짧고 실용적인 문서가 많은 책
 *  · 링크가 책을 넘어 이어질 것 (커피의 카페인 → 몸의 잠)
 *
 * 시각(updated)은 뒤로 갈수록 옛날이 되게 흘려 둔다. 전부 같은 시각이면
 * '방금 기계가 만든 것' 처럼 보인다.
 */
import type { Value } from 'platejs';
import type { WikiBook, WikiDoc, WikiInfobox } from './store';

/* ── 본문 블록 ── */
const _p = (text: string) => ({ type: 'p', children: [{ text }] });
const _h2 = (text: string) => ({ type: 'h2', children: [{ text }] });
const _h3 = (text: string) => ({ type: 'h3', children: [{ text }] });
const _quote = (text: string) => ({ type: 'blockquote', children: [{ text }] });
const _li = (text: string) => ({ type: 'p', indent: 1, listStyleType: 'disc', children: [{ text }] });
const _no = (text: string) => ({ type: 'p', indent: 1, listStyleType: 'decimal', children: [{ text }] });
/** 링크 섞인 문단 — { link: '보일 글자', to: 문서id } */
const _pl = (parts: Array<string | { link: string; to: string }>) => ({
  type: 'p',
  children: parts.map((x) => (typeof x === 'string' ? { text: x } : { type: 'a', url: `wiki://${x.to}`, children: [{ text: x.link }] })),
});

const ib = (...rows: [string, string][]): WikiInfobox => ({ rows: rows.map(([k, v]) => ({ k, v })) });


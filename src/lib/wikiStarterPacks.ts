import type { WikiPage } from '@/types/wiki';
import { newWikiId } from '@/types/wiki';

export interface StarterPack {
  id: string;
  emoji: string;
  label: string;
  description: string;
  build: () => WikiPage[];
}

function nowFactory() {
  let n = Date.now();
  return () => ++n;
}

function mkPage(p: Partial<WikiPage> & Pick<WikiPage, 'title' | 'type' | 'body'>): WikiPage {
  const t = Date.now();
  return {
    id: newWikiId(),
    title: p.title,
    aliases: p.aliases ?? [],
    type: p.type,
    status: p.status ?? 'active',
    tags: p.tags ?? [],
    body: p.body,
    refersTo: [],
    cites: [],
    inherits: [],
    similarTo: [],
    parentMocs: [],
    createdAt: t,
    updatedAt: t,
    ...p,
  };
}


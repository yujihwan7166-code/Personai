import type { WikiPage } from '@/types/wiki';
import { newWikiId } from '@/types/wiki';

export interface StarterPack {
  id: string;
  emoji: string;
  label: string;
  description: string;
  build: () => WikiPage[];
}

function nowFactory() {
  let n = Date.now();
  return () => ++n;
}

function mkPage(p: Partial<WikiPage> & Pick<WikiPage, 'title' | 'type' | 'body'>): WikiPage {
  const t = Date.now();
  return {
    id: newWikiId(),
    title: p.title,
    aliases: p.aliases ?? [],
    type: p.type,
    status: p.status ?? 'active',
    tags: p.tags ?? [],
    body: p.body,
    refersTo: [],
    cites: [],
    inherits: [],
    similarTo: [],
    parentMocs: [],
    createdAt: t,
    updatedAt: t,
    ...p,
  };
}

function enrichStarterPages(packId: StarterPack['id'], pages: WikiPage[]): WikiPage[] {
  const additions = STARTER_PACK_BODY_UPGRADES[packId] ?? {};
  const byTitle = new Map(pages.map((page) => [page.title, page]));

  return pages.map((page) => {
    const extra = additions[page.title];
    const profileGuide = page.tags.includes('atlas') && page.tags.includes('profile')
      ? STARTER_PROFILE_GUIDE
      : '';
    const bodyAdditions = [extra, profileGuide].filter(
      (value): value is string => typeof value === 'string' && value.trim().length > 0,
    );
    if (bodyAdditions.length === 0) return page;

    const next: WikiPage = {
      ...page,
      body: `${page.body.trim()}\n\n${bodyAdditions.map((value) => value.trim()).join('\n\n')}\n`,
    };

    const parentTitles = extractLinkedTitles(bodyAdditions.join('\n\n')).filter((title) => {
      const target = byTitle.get(title);
      return target && target.id !== page.id && target.type === 'moc';
    });

    if (parentTitles.length > 0) {
      const parentIds = parentTitles
        .map((title) => byTitle.get(title)?.id)
        .filter((id): id is string => Boolean(id));
      next.parentMocs = unique([...next.parentMocs, ...parentIds]);
    }

    return next;
  });
}

function extractLinkedTitles(body: string): string[] {
  const out = new Set<string>();
  const linkPattern = /\[\[([^\]|]+?)(?:\|[^\]]+?)?\]\]/g;
  let match: RegExpExecArray | null;
  while ((match = linkPattern.exec(body)) !== null) {
    const title = match[1].trim();
    if (title) out.add(title);
  }
  return [...out];
}

function unique(values: string[]): string[] {
  return [...new Set(values.filter(Boolean))];
}

